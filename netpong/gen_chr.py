def tile(rows):
    """8 row bytes (bit 7 = left pixel) -> 16 bytes, colour 1 (plane 0 only)."""
    return bytes(rows) + bytes(8)


def glyph(spec):
    rows = [int(r, 2) << 2 for r in spec.split()]   # 5 wide, 1 px left margin
    return tile([0] + rows)


chr_ = bytearray(8192)
put = lambda n, data: chr_.__setitem__(slice(n * 16, n * 16 + 16), data)
put(0x01, tile([0xFF] * 8))
put(0x02, tile([0x18] * 4 + [0] * 4))
put(0x03, tile([0xF0] * 4 + [0] * 4))
put(0x04, tile([0xF0] * 8))
put(0x05, tile([0] * 6 + [0xFF] * 2))
put(0x06, tile([0xFF] * 2 + [0] * 6))
for ch, spec in FONT.items():
    put(ord(ch), glyph(spec))

open(sys.argv[1] if len(sys.argv) > 1 else "netpong.chr", "wb").write(chr_)
